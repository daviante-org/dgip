/// Validate an uppercase 2-letter ISO 3166-1 alpha-2 country code against the active catalog set.
pub fn is_valid_country_code(code: &str, valid_codes: Option<&HashSet<String>>) -> bool {
    let cleaned = code.trim().to_uppercase();
    if cleaned.len() != 2 || !cleaned.bytes().all(|b| b.is_ascii_uppercase()) {
        return false;
    }
    if let Some(allowed) = valid_codes {
        return allowed.contains(&cleaned);
    }
    true
}

