#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_seed_catalog_counts_and_country_validation() {
        assert_eq!(DEFAULT_CONTINENTS.len(), 7);
        assert_eq!(DEFAULT_COUNTRIES.len(), 253);
        assert_eq!(DEFAULT_SPECIAL_RANGES.len(), 29);
        assert_eq!(DEFAULT_ALLOWED_HOSTS.len(), 26);
        assert_eq!(build_default_feed_sources().len(), 25);
        assert_eq!(
            build_default_config_entries(DEFAULT_BOOTSTRAP_BUNDLE_URL, 5).len(),
            30
        );

        let valid_set: HashSet<String> = DEFAULT_COUNTRIES
            .iter()
            .map(|(cc, name, _)| {
                assert_eq!(*name, name.trim());
                (*cc).to_string()
            })
            .collect();

        assert!(is_valid_country_code(" us ", Some(&valid_set)));
        assert!(is_valid_country_code("IN", Some(&valid_set)));
        assert!(!is_valid_country_code("ZZ", Some(&valid_set)));
        assert!(is_valid_country_code("ZZ", None));
        assert!(!is_valid_country_code("USA", None));
        assert!(!is_valid_country_code("1A", None));
        assert!(!is_valid_country_code("", None));
    }
}
